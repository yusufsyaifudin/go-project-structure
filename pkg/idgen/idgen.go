package idgen

import (
	"fmt"
	"sync"
	"time"

	"github.com/sony/sonyflake"
)

var (
	once     sync.Once
	instance *sonyflake.Sonyflake
)

func sf() *sonyflake.Sonyflake {
	once.Do(func() {
		var err error
		instance, err = sonyflake.New(sonyflake.Settings{
			// Don't change the start time, since it will break the order of generated ID.
			// If you want different StartTime for different use-case, try to create new helper!
			StartTime: time.Date(2026, 06, 1, 0, 0, 0, 0, time.UTC),
		})
		if err != nil {
			panic(fmt.Sprintf("idgen: failed to initialise sonyflake: %v", err))
		}
	})
	return instance
}

// NextID returns a unique, k-sortable 63-bit ID generated by Sonyflake.
// The returned value fits safely in a Postgres BIGINT column.
func NextID() (int64, error) {
	id, err := sf().NextID()
	if err != nil {
		return 0, fmt.Errorf("idgen: %w", err)
	}
	return int64(id), nil //nolint:gosec // Sonyflake IDs are 63-bit; high bit is always 0.
}
